import json, tempfile, unittest
from pathlib import Path
from unittest.mock import patch
from resumeforge import laptop
from resumeforge.models import ModelSettings, Profile, RunRequest
from resumeforge.planning import build_plan
from resumeforge.engine import run
ROOT=Path(__file__).resolve().parents[1]
class LaptopContractTests(unittest.TestCase):
    def test_two_related_statements_are_one_measured_choice(self):
        from resumeforge.layout import Typesetter
        from resumeforge.models import Candidate
        parts=['Documented the staging tests for the operations team.','Reviewed the incident runbook with the service owner.']
        c=Candidate(id='two',role_id='r',slot_id='b',evidence_ids=['b'],text=' '.join(parts),parts=parts)
        renderer=Typesetter()
        blocks=renderer.bullet_blocks(c)
        self.assertEqual([b.text for b in blocks],parts)
        self.assertEqual([b.candidate_id for b in blocks],['two','two'])
        with self.assertRaises(ValueError):
            Candidate(id='bad',role_id='r',slot_id='b',text='Different evidence.',parts=parts)

    def test_unknown_file_in_output_directory_is_preserved(self):
        with tempfile.TemporaryDirectory() as d:
            p=Path(d);file=p/'resume.pdf';file.write_bytes(b'not generated by this program')
            with self.assertRaises(FileExistsError):run(RunRequest(profile=self.profile),p)
            self.assertEqual(file.read_bytes(),b'not generated by this program')

    def setUp(self):
        self.profile=Profile.model_validate_json((ROOT/'examples/abu.profile.json').read_text())
        self.settings=ModelSettings(strategy='laptop',provider='openai-compatible',model='test')
    def test_model_cannot_assign_evidence_or_promote_an_unknown_skill(self):
        with patch.object(laptop,'ask',side_effect=[
            laptop.Focus(ordered=[999,1],terms=['Terraform'],skills=[999,1]),
            laptop.Versions(concise='Deployed Terraform for the audit.',detailed=self.profile.roles[0].bullets[0].text)]):
            p=build_plan(self.profile,'Terraform required',[],self.settings)
        self.assertEqual(p.skill_order,[self.profile.skills[0]])
        self.assertTrue(any('Deployed Terraform' in s.text for s in p.proposed_claims))
        self.assertFalse(any('Deployed Terraform' in s.text for s in p.candidates))
    def test_no_model_cannot_silently_satisfy_a_freeform_request(self):
        with tempfile.TemporaryDirectory() as d:
            r=run(RunRequest(profile=self.profile,edit_request='Remove my first job.'),Path(d))
            self.assertEqual(r['status'],'needs_review')
            self.assertFalse((Path(d)/'resume.pdf').exists())
    def test_truncated_json_retries_then_fails_closed(self):
        answer={'choices':[{'message':{'content':'{"decision":"accept","reason":"ok"}'},'finish_reason':'length'}]}
        with patch('resumeforge.planning._http',return_value=answer) as call:
            with self.assertRaisesRegex(RuntimeError,'validation twice'):
                laptop.ask(self.settings,laptop.Verdict,'Review',{},120)
        self.assertEqual(call.call_count,2)
    def test_writer_never_receives_unsupported_target_tool_for_this_job(self):
        role=self.profile.roles[1];bullet=role.bullets[0]
        idx=1+sum(len(r.bullets) for r in self.profile.roles[:1])
        def fake(settings,schema,system,data,tokens):
            if schema is laptop.Focus:return laptop.Focus(ordered=[idx],terms=['AWS','Datadog'])
            self.assertIn('Datadog',data['supported_target_terms'])
            self.assertNotIn('AWS',json.dumps(data))
            return laptop.Versions(concise=bullet.text,detailed=bullet.text)
        with patch.object(laptop,'ask',side_effect=fake):
            build_plan(self.profile,'AWS and Datadog',['AWS','Datadog'],self.settings,edit_request='Emphasize AWS and Datadog.')
    def test_instruction_reviewer_gets_explicit_job_mapping(self):
        from resumeforge.models import Candidate
        a=self.profile.roles[0];b=a.bullets[0]
        c=Candidate(id='c',role_id=a.id,slot_id=b.id,text=b.text,evidence_ids=[b.id])
        def verdict(settings,schema,system,data,tokens):
            row=data['jobs'][0]
            self.assertEqual((row['id'],row['employer'],row['dates']),(a.id,a.company,a.dates))
            self.assertIn(b.text,row['final_bullets']);self.assertTrue(data['metadata_unchanged_by_renderer'])
            return laptop.Verdict(decision='accept',reason='Exact same job and text.')
        with patch.object(laptop,'ask',side_effect=verdict):
            self.assertTrue(laptop.check_request(RunRequest(profile=self.profile,settings=self.settings,edit_request='Keep dates unchanged'),[c],[]).passed)
    def test_model_failure_does_not_leave_an_old_checked_export(self):
        with tempfile.TemporaryDirectory() as d:
            p=Path(d)
            run(RunRequest(profile=self.profile),p)
            with patch('resumeforge.engine.build_plan',side_effect=RuntimeError('model unavailable')):
                with self.assertRaises(RuntimeError):
                    run(RunRequest(profile=self.profile,settings=self.settings),p)
            self.assertFalse((p/'resume.pdf').exists())
